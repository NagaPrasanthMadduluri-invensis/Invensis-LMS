"use client";

import { useCallback, useEffect, useState } from "react";
import { usePathname } from "next/navigation";
import { fetchCertificatePendingReleaseCount } from "@/services/api/admin/admin-api";

// Dispatched after an admin generates/releases certificates, so the sidebar dot
// re-checks immediately instead of waiting for the next navigation.
export const CERTIFICATES_CHANGED_EVENT = "certificates:changed";

/**
 * Number of completed trainings that have certificates ready to release. Powers
 * the red dot next to "Certificates" in the admin sidebar. Recomputes on mount,
 * on route change (to catch certificates generated by learners submitting their
 * feedback), and whenever a CERTIFICATES_CHANGED_EVENT fires (admin
 * generate/release).
 */
export function useCertificatePendingRelease({ token }) {
  const pathname = usePathname();
  const [count, setCount] = useState(0);

  const recompute = useCallback(async () => {
    if (!token) return;
    try {
      const res = await fetchCertificatePendingReleaseCount({ token });
      setCount(res?.pending_release_trainings ?? 0);
    } catch {
      setCount(0); // never block the sidebar on a failed fetch
    }
  }, [token]);

  useEffect(() => { recompute(); }, [recompute, pathname]);

  useEffect(() => {
    const handler = () => recompute();
    window.addEventListener(CERTIFICATES_CHANGED_EVENT, handler);
    return () => window.removeEventListener(CERTIFICATES_CHANGED_EVENT, handler);
  }, [recompute]);

  return count;
}
